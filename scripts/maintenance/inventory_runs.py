#!/usr/bin/env python3
"""Create an auditable inventory of local training runs and datasets."""

from __future__ import annotations

import argparse
import json
import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml


def directory_size(path: Path) -> int:
    total = 0
    for root, _, files in os.walk(path):
        for name in files:
            file_path = Path(root) / name
            try:
                total += file_path.stat().st_size
            except FileNotFoundError:
                pass
    return total


def human_size(size: int) -> str:
    value = float(size)
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if value < 1024 or unit == "TiB":
            return f"{value:.1f} {unit}"
        value /= 1024
    raise AssertionError("unreachable")


def load_json(path: Path) -> dict[str, Any]:
    try:
        return json.loads(path.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return {}


def load_yaml(path: Path) -> dict[str, Any]:
    try:
        value = yaml.safe_load(path.read_text())
    except FileNotFoundError:
        return {}
    return value if isinstance(value, dict) else {}


def checkpoint_dirs(run_dir: Path) -> list[Path]:
    root = run_dir / "checkpoints"
    if not root.is_dir():
        return []
    return sorted(
        (path for path in root.iterdir() if path.is_dir() and path.name.isdigit()),
        key=lambda path: int(path.name),
    )


def inventory_train(train_root: Path, policy: dict[str, Any]) -> list[dict[str, Any]]:
    overrides = policy.get("runs", {})
    default_mode = policy.get("default_mode", "model_only_latest")
    records = []
    if not train_root.is_dir():
        return records

    for run_dir in sorted(path for path in train_root.iterdir() if path.is_dir()):
        checkpoints = checkpoint_dirs(run_dir)
        checkpoint_records = []
        for checkpoint in checkpoints:
            model_dir = checkpoint / "pretrained_model"
            checkpoint_records.append(
                {
                    "name": checkpoint.name,
                    "size_bytes": directory_size(checkpoint),
                    "pretrained_model_size_bytes": directory_size(model_dir) if model_dir.is_dir() else 0,
                    "has_training_state": (checkpoint / "training_state").is_dir(),
                }
            )
        records.append(
            {
                "name": run_dir.name,
                "path": str(run_dir),
                "retention_mode": overrides.get(run_dir.name, default_mode),
                "size_bytes": directory_size(run_dir),
                "latest_checkpoint": checkpoints[-1].name if checkpoints else None,
                "checkpoints": checkpoint_records,
            }
        )
    return records


def inventory_datasets(dataset_root: Path, registry: dict[str, Any]) -> list[dict[str, Any]]:
    records = []
    if not dataset_root.is_dir():
        return records

    registry_by_path = {
        Path(entry["path"]): (dataset_id, entry)
        for dataset_id, entry in registry.get("datasets", {}).items()
    }
    for info_path in sorted(dataset_root.glob("**/meta/info.json")):
        dataset_dir = info_path.parent.parent
        relative_path = dataset_dir.relative_to(dataset_root)
        info = load_json(info_path)
        dataset_id, entry = registry_by_path.get(relative_path, (str(relative_path), {}))
        expected = entry.get("metadata", {})
        records.append(
            {
                "name": dataset_id,
                "path": str(dataset_dir),
                "relative_path": str(relative_path),
                "role": entry.get("role", "unregistered"),
                "retention": entry.get("retention", "unregistered"),
                "size_bytes": directory_size(dataset_dir),
                "total_episodes": info.get("total_episodes", expected.get("episodes")),
                "total_frames": info.get("total_frames", expected.get("frames")),
                "total_tasks": info.get("total_tasks", expected.get("tasks")),
                "fps": info.get("fps"),
            }
        )
    return records


def render_markdown(inventory: dict[str, Any]) -> str:
    lines = [
        "# Project Asset Inventory",
        "",
        f"Generated: `{inventory['generated_at']}`",
        "",
        "This file is generated by `scripts/maintenance/inventory_runs.py`.",
        "",
        "## Training Runs",
        "",
        "| Run | Retention | Latest | Checkpoints | Total | Latest model |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for run in inventory["training_runs"]:
        latest = run["checkpoints"][-1] if run["checkpoints"] else None
        lines.append(
            "| "
            + " | ".join(
                [
                    f"`{run['name']}`",
                    run["retention_mode"],
                    run["latest_checkpoint"] or "-",
                    str(len(run["checkpoints"])),
                    human_size(run["size_bytes"]),
                    human_size(latest["pretrained_model_size_bytes"]) if latest else "-",
                ]
            )
            + " |"
        )

    lines.extend(
        [
            "",
            "## Datasets",
            "",
            "| Dataset | Role | Retention | Episodes | Frames | Tasks | Size |",
            "|---|---|---|---:|---:|---:|---:|",
        ]
    )
    for dataset in inventory["datasets"]:
        lines.append(
            "| "
            + " | ".join(
                [
                    f"`{dataset['name']}`",
                    dataset["role"],
                    dataset["retention"],
                    str(dataset["total_episodes"] if dataset["total_episodes"] is not None else "-"),
                    str(dataset["total_frames"] if dataset["total_frames"] is not None else "-"),
                    str(dataset["total_tasks"] if dataset["total_tasks"] is not None else "-"),
                    human_size(dataset["size_bytes"]),
                ]
            )
            + " |"
        )
    lines.append("")
    return "\n".join(lines)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs-root", type=Path, default=Path("runs"))
    parser.add_argument(
        "--policy",
        type=Path,
        default=Path("scripts/maintenance/checkpoint_retention.json"),
    )
    parser.add_argument("--dataset-registry", type=Path, default=Path("configs/datasets.yaml"))
    parser.add_argument("--output-dir", type=Path, default=Path("runs/manifests"))
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    runs_root = args.runs_root.resolve()
    policy = load_json(args.policy)
    dataset_registry = load_yaml(args.dataset_registry)
    inventory = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "runs_root": str(runs_root),
        "training_runs": inventory_train(runs_root / "train", policy),
        "datasets": inventory_datasets(runs_root / "dataset", dataset_registry),
    }

    args.output_dir.mkdir(parents=True, exist_ok=True)
    json_path = args.output_dir / "project_inventory.json"
    markdown_path = args.output_dir / "project_inventory.md"
    json_path.write_text(json.dumps(inventory, indent=2) + "\n")
    markdown_path.write_text(render_markdown(inventory))
    print(f"Wrote {json_path}")
    print(f"Wrote {markdown_path}")


if __name__ == "__main__":
    main()
